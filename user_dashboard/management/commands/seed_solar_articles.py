    # =========================================================
    # تنظيف اسم الصورة
    # =========================================================
    def safe_filename(self, title, index):
        clean = re.sub(r"[^\w\u0600-\u06FF-]+", "_", title)
        clean = clean.strip("_")
        return f"article_{index:03d}_{clean[:50]}.jpg"

    # =========================================================
    # تحميل صورة
    # =========================================================
    def download_image(self, url):
        try:
            request = urllib.request.Request(
                url,
                headers={
                    "User-Agent": "Mozilla/5.0"
                }
            )

            context = ssl._create_unverified_context()

            with urllib.request.urlopen(
                request,
                timeout=30,
                context=context
            ) as response:

                image_data = response.read()

                if not image_data:
                    return None

                return image_data

        except Exception as e:
            self.stdout.write(
                self.style.WARNING(
                    f"⚠️ فشل تحميل الصورة: {str(e)}"
                )
            )
            return None

    # =========================================================
    # التنفيذ
    # =========================================================
    @transaction.atomic
    def handle(self, *args, **options):

        self.stdout.write("")
        self.stdout.write(
            self.style.SUCCESS(
                "☀️ بدء إضافة مقالات الطاقة الشمسية..."
            )
        )
        self.stdout.write("")

        total = len(self.ARTICLES)

        self.stdout.write(
            f"عدد المقالات الموجودة في الملف: {total}"
        )

        if total < 100:
            self.stdout.write(
                self.style.ERROR(
                    f"❌ الملف يحتوي على {total} مقالة فقط، وليس 100."
                )
            )
            return

        created_count = 0
        updated_count = 0
        image_count = 0
        image_failed = 0

        for index, (title, content) in enumerate(
            self.ARTICLES[:100],
            start=1
        ):

            self.stdout.write(
                f"[{index}/100] {title}"
            )

            # -------------------------------------------------
            # البحث عن المقالة إذا كانت موجودة
            # -------------------------------------------------
            article = SolarArticle.objects.filter(
                title=title
            ).first()

            if article:
                article.content = content
                article.is_published = True
                article.save(
                    update_fields=[
                        "content",
                        "is_published"
                    ]
                )

                updated_count += 1

            else:
                article = SolarArticle.objects.create(
                    title=title,
                    content=content,
                    is_published=True
                )

                created_count += 1

            # -------------------------------------------------
            # اختيار صورة بالتناوب
            # -------------------------------------------------
            image_url = self.IMAGE_URLS[
                (index - 1) % len(self.IMAGE_URLS)
            ]

            # تحميل الصورة فقط إذا المقالة لا تحتوي صورة
            if not article.image:

                image_data = self.download_image(
                    image_url
                )

                if image_data:

                    filename = self.safe_filename(
                        title,
                        index
                    )

                    article.image.save(
                        filename,
                        ContentFile(image_data),
                        save=True
                    )

                    image_count += 1

                    self.stdout.write(
                        self.style.SUCCESS(
                            "   ✓ تم تحميل الصورة"
                        )
                    )

                else:

                    image_failed += 1

                    self.stdout.write(
                        self.style.WARNING(
                            "   ⚠️ لم يتم تحميل الصورة"
                        )
                    )

        # =====================================================
        # النتيجة النهائية
        # =====================================================

        self.stdout.write("")
        self.stdout.write("=" * 60)

        self.stdout.write(
            self.style.SUCCESS(
                "☀️ تم الانتهاء بنجاح!"
            )
        )

        self.stdout.write(
            f"📚 المقالات الجديدة: {created_count}"
        )

        self.stdout.write(
            f"🔄 المقالات التي تم تحديثها: {updated_count}"
        )

        self.stdout.write(
            f"🖼️ الصور التي تم تحميلها: {image_count}"
        )

        self.stdout.write(
            f"⚠️ الصور التي فشل تحميلها: {image_failed}"
        )

        self.stdout.write("=" * 60)
        self.stdout.write("")